// Re-extracts the prototype's sample data into db/seed/data/*.json, so seed data is never retyped.
//   node seed/extract-from-prototype.mjs [baseUrlOrDir]
// The prototype files assign window.SFData.<name>; they are evaluated with a stub window.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const URL_BASE = 'https://www.thehigherwave.com/prototypes/productivity/research-driven-process';
const BASE = process.argv[2] || URL_BASE;
const here = dirname(fileURLToPath(import.meta.url));

async function load(name) {
  if (/^https?:/.test(BASE)) {
    const res = await fetch(`${BASE}/data/${name}.js`);
    if (!res.ok) throw new Error(`${name}.js: HTTP ${res.status}`);
    return res.text();
  }
  return readFileSync(join(BASE, 'data', `${name}.js`), 'utf8');
}

const stamp = new Date().toISOString().slice(0, 10);
for (const [file, key] of [['research', 'research'], ['boards', 'boards'], ['platformInsights', 'platformInsights']]) {
  const win = { SFData: {} };
  new Function('window', await load(file))(win);
  const out = { _source: `${URL_BASE}/data/${file}.js`, _extracted: stamp, ...win.SFData[key] };
  writeFileSync(join(here, 'data', `${file}.json`), JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote data/${file}.json (${Object.keys(out).length - 2} keys)`);
}

// The simulated analysis also needs the prototype's theme definitions and effort estimates at run time. They are
// written as a plain module so the API can import them without JSON import attributes.
const research = JSON.parse(readFileSync(join(here, 'data', 'research.json'), 'utf8'));
const config = `// Generated by db/seed/extract-from-prototype.mjs from the prototype's research.js. Do not edit by hand.
// The simulated analysis's theme definitions (keywords, description, opportunity), effort estimates and the
// five progress step titles. A real model replaces the analysis; this file goes with it.
export const THEMES = ${JSON.stringify(research.TH, null, 2)};
export const EFFORT = ${JSON.stringify(research.EFF, null, 2)};
export const STEP_TITLES = ${JSON.stringify(research.BUSY, null, 2)};
`;
writeFileSync(join(here, '..', '..', 'shared', 'stub-config.mjs'), config);
console.log('wrote shared/stub-config.mjs');
